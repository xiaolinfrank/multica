import { expect, test } from "@playwright/test";
import { TestApiClient } from "./fixtures";

test.use({ viewport: { width: 1600, height: 1100 }, locale: "en-US", timezoneId: "Asia/Shanghai", trace: "retain-on-failure" });

test("restores a personal scoped view and holds a read-only report until explicit refresh", async ({ page }, testInfo) => {
  test.setTimeout(120_000);
  const api = new TestApiClient(); const run = `${Date.now().toString(36)}-${process.pid}`;
  const auth = await api.login(`e2e-report-${run}@multica.ai`, "Report fixture reviewer");
  let ownsWorkspace = false;
  try {
    const workspace = await api.createWorkspace(`Delivery reporting ${run}`, `e2e-report-${run}`); ownsWorkspace = true;
    await api.markUserOnboarded(); await api.updateCockpitBoard({ title: "Delivery decision workbench", goal_title: "Confirm the delivery evidence", goal_date: "2026-12-31" });
    const project = await api.createProject("Evidence programme"), module = await api.createModule(project.id, "Delivery module");
    const root = await api.createCockpitNode({ code: "EP", name: project.title, project_id: project.id });
    const group = await api.createCockpitNode({ code: "DM", name: module.title, module_id: module.id, parent_id: root.id });
    const leaf = await api.createCockpitNode({ code: "DE", name: "Confirm delivery readiness", parent_id: group.id });
    const meeting = await api.createCockpitMeeting({ title: "Evidence decision meeting", meet_date: new Date().toISOString().slice(0, 10) });
    await api.appendCockpitMeetingNode(meeting.id, leaf.id);
    await api.seedPendingMeetingReview(meeting.id, auth.user.id, "# Fixed review evidence\n\nThis remains a draft until a human decision.");
    const token = api.getToken(); if (!token) throw new Error("Fixture token missing");
    await page.addInitScript((value) => { localStorage.setItem("multica_token", value); localStorage.setItem("multica:chat:isOpen", "false"); document.cookie = "multica-locale=en; path=/"; }, token);
    const base = `/${workspace.slug}/cockpit`, scoped = `${base}?project=${project.id}&module=${module.id}`;
    await page.goto(scoped, { waitUntil: "domcontentloaded" });
    await page.getByRole("button", { name: "Team queue", exact: true }).click();
    await page.getByRole("button", { name: "View all next actions", exact: true }).click();
    await page.getByRole("combobox", { name: "Work type", exact: true }).click();
    await page.getByRole("option", { name: "Meeting workflows", exact: true }).click();
    const queue = page.getByRole("region", { name: "Next actions", exact: true });
    await expect(queue.getByRole("article")).toHaveCount(1);
    await page.getByRole("button", { name: "Saved views", exact: true }).click();
    await page.getByRole("button", { name: "Save current view", exact: true }).click();
    await page.getByRole("textbox", { name: "View name", exact: true }).fill("Evidence review queue");
    await expect(page.getByText("Saved on this device for your account and workspace. Not shared or synced.", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Save view", exact: true }).click();
    await expect(page.getByRole("button", { name: "Apply view Evidence review queue", exact: true })).toBeVisible();
    await page.keyboard.press("Escape");
    await page.goto(`${base}?tab=plan`, { waitUntil: "domcontentloaded" });
    await page.reload({ waitUntil: "domcontentloaded" });
    await page.getByRole("button", { name: "Saved views", exact: true }).click();
    await page.getByRole("button", { name: "Apply view Evidence review queue", exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`project=${project.id}.*module=${module.id}`));
    await expect(page.getByRole("button", { name: "Team queue", exact: true })).toHaveAttribute("aria-pressed", "true");
    await expect(page.getByRole("button", { name: "Back to work overview", exact: true })).toBeVisible();
    await expect(page.getByRole("combobox", { name: "Work type", exact: true })).toContainText("Meeting workflows");
    await expect(queue.getByRole("article")).toHaveCount(1);
    await page.screenshot({ path: testInfo.outputPath("saved-scoped-review-view.png") });

    const exactReturn = `${base}?meeting=${meeting.id}&meeting_view=resources&project=${project.id}&module=${module.id}`;
    await page.goto(exactReturn, { waitUntil: "domcontentloaded" });
    await expect(page.getByRole("region", { name: "Meeting materials", exact: true })).toBeVisible();
    const reportReads: string[] = [], forbidden: string[] = [];
    page.on("request", (request) => { if (!page.url().includes("report=1")) return; const url = new URL(request.url());
      if (url.pathname === "/api/cockpit/overview") reportReads.push(request.url());
      if (url.pathname === "/api/cockpit" || url.pathname === "/api/cockpit/plan" || (url.pathname.startsWith("/api/cockpit/") && request.method() !== "GET")) forbidden.push(`${request.method()} ${url.pathname}`);
    });
    await page.getByRole("link", { name: "Project report", exact: true }).click();
    const report = page.getByRole("region", { name: "Project report", exact: true });
    await expect(report.getByText("Confirm the delivery evidence", { exact: true })).toBeVisible();
    await expect(report.getByRole("link", { name: "Return to work", exact: true })).toHaveAttribute("href", exactReturn);
    const meetingWindow = report.locator("section").filter({ has: page.getByRole("heading", { name: "Meeting window", exact: true }) });
    await expect(meetingWindow.getByText("Evidence decision meeting", { exact: true })).toBeVisible();
    expect(reportReads).toHaveLength(1); const firstQuery = new URL(reportReads[0]!).searchParams;
    expect(firstQuery.get("project_id")).toBe(project.id); expect(firstQuery.get("module_id")).toBe(module.id); expect(firstQuery.get("attention_view")).toBe("team");
    const backgroundContext = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/cockpit/context");
    await api.updateCockpitBoard({ goal_title: "Ready for a new decision" });
    expect((await backgroundContext).ok()).toBe(true);
    await expect(report.getByText("Confirm the delivery evidence", { exact: true })).toBeVisible();
    expect(reportReads).toHaveLength(1);
    const refreshed = page.waitForResponse((response) => new URL(response.url()).pathname === "/api/cockpit/overview");
    await report.getByRole("button", { name: "Refresh report", exact: true }).click();
    expect((await refreshed).ok()).toBe(true);
    await expect(report.getByText("Ready for a new decision", { exact: true })).toBeVisible();
    expect(reportReads).toHaveLength(2); expect(new URL(reportReads[1]!).searchParams.get("as_of")).toBe(firstQuery.get("as_of"));
    expect(forbidden).toEqual([]);
    await page.screenshot({ path: testInfo.outputPath("scoped-project-report.png"), fullPage: true });
    await report.getByRole("link", { name: "Return to work", exact: true }).click();
    await expect(page).toHaveURL((url) => url.pathname + url.search === exactReturn);
    await expect(page.getByRole("region", { name: "Meeting materials", exact: true })).toBeVisible();
    expect(await api.getWorkspaceAgentRunCount()).toBe(0);
  } finally { if (ownsWorkspace) await api.cleanupCreatedWorkspace(); }
});
